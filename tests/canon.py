"""What tests/export_canon.py and tests/run_canon.py share: the canonical tables of a
domain, their column types in standard SQL, and where their CSV files are.

A canonical table holds the columns an Ossie model reads, in the order of the
packages' contracts (tests/check_contracts.py), and no others. tests/<domain>/tables.sql
declares them in standard SQL; tests/<package>/canon/<table>.csv and
tests/<package>/canon_windows/<table>.csv hold their rows over the fixtures.
"""
import pathlib
import re

import yaml

import check_contracts

ROOT = check_contracts.ROOT
NULL = r"\N"  # a NULL in the CSV files


def standard_type(clickhouse_type):
    """(type in standard SQL, nullable) for a ClickHouse type of a contract."""
    spelled = check_contracts.normal(clickhouse_type)  # as check_contracts compares them: no spaces
    nullable = spelled.startswith("Nullable(")
    inner = spelled[len("Nullable("):-1] if nullable else spelled
    inner = re.sub(r"^LowCardinality\((.*)\)$", r"\1", inner)
    decimal = re.fullmatch(r"Decimal\((\d+),(\d+)\)", inner)
    if decimal:
        return f"DECIMAL({decimal[1]}, {decimal[2]})", nullable
    known = {"String": "VARCHAR", "Int64": "BIGINT", "UInt64": "BIGINT", "Bool": "BOOLEAN",
             "Date": "DATE", "DateTime('UTC')": "TIMESTAMP WITH TIME ZONE"}
    if inner not in known:
        raise SystemExit(f"{clickhouse_type} has no type in standard SQL; decide how to carry it")
    return known[inner], nullable


def canon_tables(package):
    """{table: [(column, ClickHouse type), ...]} of the Ossie model the package serves, in the contract's order."""
    model_file = yaml.safe_load((ROOT / "sources" / package / "deployment.yml").read_text())["model"]
    declared = check_contracts.contracts(ROOT / "sources" / package)
    return {table: [(c, dict(declared[table])[c]) for c in columns]
            for table, columns in check_contracts.canonical_columns(ROOT / model_file).items()}, model_file


def domain(model_file):
    return pathlib.PurePosixPath(model_file).stem


def ddl(tables):
    """tables.sql: one CREATE TABLE per table, a column a line, NOT NULL where the contract is not Nullable."""
    out = ["-- The canonical tables of the domain, in standard SQL. Generated by tests/export_canon.py\n"
           "-- from the contracts of the packages; a NULL in the CSV files is \\N.\n"]
    for table, columns in tables.items():
        lines = []
        for column, clickhouse_type in columns:
            sql_type, nullable = standard_type(clickhouse_type)
            lines.append(f"    {column} {sql_type}{'' if nullable else ' NOT NULL'}")
        out.append(f"CREATE TABLE {table} (\n" + ",\n".join(lines) + "\n);\n")
    return "\n".join(out)


def csv_dir(package, windows):
    return ROOT / "tests" / package / ("canon_windows" if windows else "canon")
